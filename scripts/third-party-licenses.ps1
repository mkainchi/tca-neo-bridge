<#
.SYNOPSIS
  Writes THIRD_PARTY_LICENSES.md: every Rust crate compiled into neo-daemon.exe and neo-config.exe, with the licence
  files each crate ships (identical texts printed once).
.DESCRIPTION
  Run from anywhere after `cargo fetch`; scripts\package.ps1 runs it before every release, so the zip always carries
  the list for exactly what it contains. Crates that ship no licence file are listed with the licence they declare.
#>
$ErrorActionPreference = 'Stop'
$env:PATH = "$env:USERPROFILE\.cargo\bin;$env:PATH"
$root = Resolve-Path (Join-Path $PSScriptRoot '..')
$target = 'x86_64-pc-windows-msvc'
Push-Location $root
try {
    $meta = cargo metadata --format-version 1 --filter-platform $target | ConvertFrom-Json
    $used = foreach ($package in 'neo-daemon', 'neo-config') {
        cargo tree -p $package -e normal --target $target --prefix none --no-dedupe | ForEach-Object { ($_ -split ' ')[0..1] -join ' ' }
    }
} finally {
    Pop-Location
}
$crates = foreach ($entry in $used | Sort-Object -Unique) {
    $name, $version = $entry -split ' '
    $package = $meta.packages | Where-Object { $_.name -eq $name -and $_.version -eq $version.TrimStart('v') } | Select-Object -First 1
    # Workspace crates (no source) are this project's own, under its MIT licence.
    if ($package -and $package.source) { $package }
}

$texts = [ordered]@{}
$rows = foreach ($crate in $crates | Sort-Object name, version) {
    $files = Get-ChildItem (Split-Path $crate.manifest_path) -File | Where-Object { $_.Name -match '^(LICEN[CS]E|COPYING|NOTICE|UNLICENSE)' } | Sort-Object Name
    foreach ($file in $files) {
        $text = ((Get-Content $file.FullName -Raw) -replace "`r`n", "`n").Trim()
        if (-not $texts.Contains($text)) { $texts[$text] = [System.Collections.Generic.List[string]]::new() }
        $texts[$text].Add("$($crate.name) $($crate.version) ($($file.Name))")
    }
    $note = if ($files) { '' } else { ' (no licence file in the package; the same standard texts below apply)' }
    "| $($crate.name) | $($crate.version) | $($crate.license)$note | $($crate.repository) |"
}

$out = [System.Collections.Generic.List[string]]::new()
$out.Add('# Third-party licences')
$out.Add('')
$out.Add('Generated by `scripts/third-party-licenses.ps1`; do not edit. Every Rust crate compiled into `neo-daemon.exe` and `neo-config.exe`, then each licence file those crates ship, with the crates it belongs to. Where a crate offers a choice of licences, it is used under the MIT licence if MIT is one of the choices, otherwise under Apache-2.0.')
$out.Add('')
$out.Add('| Crate | Version | Licence | Source |')
$out.Add('| --- | --- | --- | --- |')
$rows | ForEach-Object { $out.Add($_) }
$out.Add('')
$out.Add('## Licence texts')
foreach ($text in $texts.Keys) {
    $out.Add('')
    $out.Add("### $($texts[$text] -join ', ')")
    $out.Add('')
    $out.Add('```text')
    $out.Add($text)
    $out.Add('```')
}
$path = Join-Path $root 'THIRD_PARTY_LICENSES.md'
[IO.File]::WriteAllText($path, ($out -join "`n") + "`n")
"Wrote $path ($($crates.Count) crates, $($texts.Count) distinct licence texts)"
