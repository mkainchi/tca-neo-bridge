# Builds neohid.dll + neohid.inf + an unsigned neohid.cat into driver\out (no WDK Visual Studio extension needed).
# Runs the frame parser unit test first. Signing happens on the user's PC (scripts\install-driver.ps1).
param([string]$DriverVersion = '0.1.0.0')
$ErrorActionPreference = 'Stop'
$here = $PSScriptRoot
$out = Join-Path $here 'out'
$kit = 'C:\Program Files (x86)\Windows Kits\10'
$sdk = '10.0.26100.0'
$umdf = '2.33'

# Single source of truth for the report descriptor: neo-descriptor.hex (the NEO-compatible HID report descriptor).
$hex = (Get-Content (Join-Path $here 'neo-descriptor.hex') -Raw).Trim()
$bytes = for ($i = 0; $i -lt $hex.Length; $i += 2) { '0x' + $hex.Substring($i, 2) }
$lines = for ($i = 0; $i -lt $bytes.Count; $i += 16) { '    ' + (($bytes[$i..([Math]::Min($i + 15, $bytes.Count - 1))]) -join ', ') + ',' }
Set-Content (Join-Path $here 'descriptor.h') ("/* Generated by build.ps1 from neo-descriptor.hex ($($bytes.Count) bytes). Do not edit. */`n#pragma once`nstatic const UCHAR NeoReportDescriptor[] = {`n" + ($lines -join "`n") + "`n};`n") -NoNewline

# MSVC environment.
$vs = & "${env:ProgramFiles(x86)}\Microsoft Visual Studio\Installer\vswhere.exe" -products * -latest -requires Microsoft.VisualStudio.Component.VC.Tools.x86.x64 -property installationPath
cmd /c "`"$vs\VC\Auxiliary\Build\vcvars64.bat`" >nul && set" | ForEach-Object { if ($_ -match '^([^=]+)=(.*)$') { Set-Item "env:$($matches[1])" $matches[2] } }

New-Item -ItemType Directory -Force $out | Out-Null
Push-Location $out
try {
    cl /nologo /W4 /WX /Fe:frame_test.exe (Join-Path $here 'frame_test.c'); if ($LASTEXITCODE) { throw 'frame_test build failed' }
    .\frame_test.exe; if ($LASTEXITCODE) { throw 'frame_test failed' }

    $includes = @("$kit\Include\wdf\umdf\$umdf", "$kit\Include\$sdk\um", "$kit\Include\$sdk\shared", "$kit\Include\$sdk\km", $here) | ForEach-Object { "/I$_" }
    $defines = @('UMDF_VERSION_MAJOR=2', 'UMDF_VERSION_MINOR=33', 'UMDF_USING_NTSTATUS', '_UNICODE', 'UNICODE', 'WIN32_LEAN_AND_MEAN') | ForEach-Object { "/D$_" }
    cl /nologo /c /W4 /WX /wd4324 /O2 /GS /guard:cf /Qspectre /sdl /Zi /MT @includes @defines (Join-Path $here 'neohid.c'); if ($LASTEXITCODE) { throw 'compile failed' }
    $libs = @("$kit\Lib\wdf\umdf\x64\$umdf\WdfDriverStubUm.lib", "$kit\Lib\$sdk\um\x64\ntdll.lib", "$kit\Lib\$sdk\um\x64\mincore.lib")
    link /nologo /DLL /OUT:neohid.dll /DEBUG /PDB:neohid.pdb /PDBALTPATH:neohid.pdb /DYNAMICBASE /NXCOMPAT /GUARD:CF /SUBSYSTEM:WINDOWS neohid.obj @libs; if ($LASTEXITCODE) { throw 'link failed' }

    # Inf2Cat rejects a DriverVer later than today in UTC, so stamp the UTC date.
    $driverDate = (Get-Date).ToUniversalTime().ToString('MM/dd/yyyy', [Globalization.CultureInfo]::InvariantCulture)
    Copy-Item (Join-Path $here 'neohid.inx') neohid.inf -Force
    & "$kit\bin\$sdk\x64\stampinf.exe" -f neohid.inf -a amd64 -u "$umdf.0" -d $driverDate -v $DriverVersion; if ($LASTEXITCODE) { throw 'stampinf failed' }
    & "$kit\Tools\$sdk\x64\infverif.exe" /w /v neohid.inf; if ($LASTEXITCODE) { throw 'infverif failed' }
    Remove-Item neohid.cat -ErrorAction SilentlyContinue
    $package = Join-Path $out 'package'
    Remove-Item -Recurse -Force $package -ErrorAction SilentlyContinue
    New-Item -ItemType Directory $package | Out-Null
    Copy-Item neohid.dll, neohid.inf $package
    & "$kit\bin\$sdk\x86\Inf2Cat.exe" /driver:$package /os:10_CO_X64,10_NI_X64,10_GE_X64 /verbose | Select-Object -Last 3; if ($LASTEXITCODE) { throw 'inf2cat failed' }
    Get-FileHash "$package\*" -Algorithm SHA256 | ForEach-Object { '{0}  {1}' -f $_.Hash.ToLower(), (Split-Path $_.Path -Leaf) }
} finally {
    Pop-Location
}
